package com.zuoqirun.lyricscompanion;

import org.json.JSONArray;
import org.json.JSONObject;
import org.junit.Test;

import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.FileInputStream;
import java.io.InputStream;
import java.util.Iterator;
import java.util.zip.GZIPInputStream;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertNotNull;
import static org.junit.Assert.assertTrue;

public class FoliaOriginalSonnetGeometryTest {
    @Test public void everyMotifUsesCurrentSeedAndViewportExactlyLikeTheOriginalRecipes() throws Exception {
        // Generated by running pinned original TypeScript, not by recording/replaying the IR.
        // All 100 motifs, portrait/landscape, all 7 shot families, molecule and HUD subvariants.
        FoliaOriginalSonnetGeometryProgram program = program();
        try (InputStream resource = getClass().getResourceAsStream("/folia/sonnet-geometry-oracle.json.gz")) {
            assertNotNull(resource);
            JSONObject root = new JSONObject(read(new GZIPInputStream(resource)));
            assertEquals("92792519ce4b72d540e69f3634aa408810c6e0f6", root.getString("revision"));
            JSONArray fixtures = root.getJSONArray("fixtures");
            assertEquals(218, fixtures.length());
            for (int i = 0; i < fixtures.length(); i++) {
                JSONObject fixture = fixtures.getJSONObject(i);
                JSONObject actual = program.build(fixture.getString("kind"), fixture.getDouble("width"),
                        fixture.getDouble("height"), fixture.getLong("seed"));
                assertEquals("geometry random calls " + i, fixture.getInt("randomCalls"), actual.getInt("randomCalls"));
                compare("fixture " + i + " seed " + fixture.getLong("seed"), fixture.getJSONArray("nodes"), actual.getJSONArray("nodes"));
            }
        }
    }

    @Test public void rebuildAndDistantSeekKeepTheSamePathsWithoutFourSeedQuantization() throws Exception {
        FoliaOriginalSonnetGeometryProgram program = program();
        JSONObject a = program.build("type-impact", 971, 547, 1234503);
        program.build("editorial-column", 431, 997, 0xffffffffL);
        JSONObject b = program.build("type-impact", 971, 547, 1234503);
        compare("rebuild", a, b);
        // Same motif (3), a different molecule cycle: no repeated four-sample recording selection.
        JSONObject c = program.build("type-impact", 971, 547, 1234603);
        assertTrue(!a.toString().equals(c.toString()));
    }

    @Test public void measuredTypographyMatchesOriginalRolesFlowFittingAndDecorationPlacements() throws Exception {
        FoliaOriginalSonnetGeometryProgram program = program();
        try (InputStream resource = getClass().getResourceAsStream("/folia/sonnet-typography-oracle.json.gz")) {
            assertNotNull(resource);
            JSONArray fixtures = new JSONObject(read(new GZIPInputStream(resource))).getJSONArray("fixtures");
            assertEquals(140, fixtures.length());
            for (int index = 0; index < fixtures.length(); index++) {
                JSONObject fixture = fixtures.getJSONObject(index), options = fixture.getJSONObject("options");
                JSONArray actual = program.typography(options.getJSONArray("lines"), options.getString("shotKind"),
                        options.getString("paragraphKind"), options.getDouble("width"), options.getDouble("height"),
                        options.getDouble("baseFontSize"), (text, size, weight) -> {
                            double units = 0;
                            for (int i = 0; i < text.length();) {
                                int cp = text.codePointAt(i); i += Character.charCount(cp);
                                units += cp >= 0x2e80 ? 1 : Character.isWhitespace(cp) ? 0.32 : 0.55;
                            }
                            return units * size * (1 + weight / 10000.0);
                        });
                compare("typography " + index + " " + options.getString("shotKind"), fixture.getJSONArray("placements"), actual);
            }
        }
    }

    @Test public void allFourFramesMatchOriginalOrnamentsAndTheirElasticTiming() throws Exception {
        try (InputStream resource = getClass().getResourceAsStream("/folia/sonnet-frame-oracle.json.gz")) {
            assertNotNull(resource);
            JSONArray fixtures = new JSONObject(read(new GZIPInputStream(resource))).getJSONArray("fixtures");
            assertEquals(84, fixtures.length());
            for (int index = 0; index < fixtures.length(); index++) {
                JSONObject fixture = fixtures.getJSONObject(index);
                JSONArray actual = new JSONArray();
                FoliaOriginalSonnetFrameDecor.Target target = new FoliaOriginalSonnetFrameDecor.Target() {
                    @Override public void path(double[] points, boolean fill, double width, double alpha) {
                        try { actual.put(new JSONObject().put("points", new JSONArray(points)).put("fill", fill).put("width", width).put("alpha", alpha)); }
                        catch (Exception error) { throw new AssertionError(error); }
                    }
                    @Override public void circle(double x, double y, double radius, double alpha, boolean white) {
                        try { actual.put(new JSONObject().put("x", x).put("y", y).put("r", radius).put("alpha", alpha).put("white", white)); }
                        catch (Exception error) { throw new AssertionError(error); }
                    }
                };
                FoliaOriginalSonnetFrameDecor.draw(target, fixture.getDouble("measuredWidth"), fixture.getDouble("measuredHeight"),
                        fixture.getDouble("rotation"), fixture.getDouble("fontSize"), fixture.getInt("variant"), fixture.getDouble("progress"));
                compare("frame " + index, fixture.getJSONArray("draws"), actual);
            }
        }
    }

    @Test public void ordinaryTextBackdropsMatchEveryOriginalHollowAndSolidPlan() throws Exception {
        FoliaOriginalSonnetGeometryProgram program = program();
        try (InputStream resource = getClass().getResourceAsStream("/folia/sonnet-text-geometry-oracle.json.gz")) {
            assertNotNull(resource);
            JSONArray fixtures = new JSONObject(read(new GZIPInputStream(resource))).getJSONArray("fixtures");
            assertEquals(240, fixtures.length());
            for (int index = 0; index < fixtures.length(); index++) {
                JSONObject fixture = fixtures.getJSONObject(index);
                JSONObject actual = program.textFixedGeometry(fixture.getLong("seed"), fixture.getBoolean("chorus"),
                        fixture.getDouble("fontSize"), fixture.getDouble("layoutWidth"));
                compare("text fixed geometry " + index, fixture.getJSONObject("node"), actual);
            }
        }
    }

    @Test public void guidesMatchOriginalCometsThreadsSplinesBurstsAndRandomConsumptionOrder() throws Exception {
        try (InputStream resource = getClass().getResourceAsStream("/folia/sonnet-guide-oracle.json.gz")) {
            assertNotNull(resource);
            JSONArray fixtures = new JSONObject(read(new GZIPInputStream(resource))).getJSONArray("fixtures");
            assertEquals(64, fixtures.length());
            for (int index = 0; index < fixtures.length(); index++) {
                JSONObject fixture = fixtures.getJSONObject(index);
                long[] randomState = {fixture.getLong("seed") & 0xffffffffL};
                JSONArray randomTrace = new JSONArray();
                FoliaOriginalSonnetGuide guide = new FoliaOriginalSonnetGuide(fixture.getBoolean("hero"), fixture.getDouble("size"),
                        fixture.getDouble("enterX"), fixture.getDouble("enterY"), fixture.getDouble("timingPhase"), () -> {
                    randomState[0] = (randomState[0] * 1664525L + 1013904223L) & 0xffffffffL;
                    double next = randomState[0] / 4294967296.0;
                    try { randomTrace.put(next); }
                    catch (Exception error) { throw new AssertionError(error); }
                    return next;
                });
                compare("guide random trace " + index, fixture.getJSONArray("randomValues"), randomTrace);
                JSONArray actual = new JSONArray();
                FoliaOriginalSonnetGuide.Target target = new FoliaOriginalSonnetGuide.Target() {
                    @Override public void line(double x1, double y1, double x2, double y2, double width, double alpha, boolean white) {
                        try { actual.put(new JSONObject().put("op", "line").put("x1", x1).put("y1", y1).put("x2", x2).put("y2", y2).put("width", width).put("alpha", alpha).put("white", white)); }
                        catch (Exception error) { throw new AssertionError(error); }
                    }
                    @Override public void circle(double x, double y, double radius, boolean fill, double width, double alpha, boolean white) {
                        try { actual.put(new JSONObject().put("op", "circle").put("x", x).put("y", y).put("radius", radius).put("fill", fill).put("width", width).put("alpha", alpha).put("white", white)); }
                        catch (Exception error) { throw new AssertionError(error); }
                    }
                    @Override public void particle(int kind, double size, double x, double y, double rotation, double scale, double alpha) {
                        try { actual.put(new JSONObject().put("op", "particle").put("kind", kind).put("size", size).put("x", x).put("y", y).put("rotation", rotation).put("scale", scale).put("alpha", alpha)); }
                        catch (Exception error) { throw new AssertionError(error); }
                    }
                };
                guide.draw(target, fixture.getDouble("progress"));
                compare("guide " + index, fixture.getJSONArray("draws"), actual);
            }
        }
    }

    private FoliaOriginalSonnetGeometryProgram program() throws Exception {
        File file = new File("src/main/assets/folia_original_canvas/sonnet/geometry-program.json");
        if (!file.isFile()) file = new File("app", file.getPath());
        try (InputStream input = new FileInputStream(file)) { return new FoliaOriginalSonnetGeometryProgram(read(input)); }
    }

    private static String read(InputStream input) throws Exception {
        ByteArrayOutputStream output = new ByteArrayOutputStream();
        byte[] buffer = new byte[8192];
        int count;
        while ((count = input.read(buffer)) != -1) output.write(buffer, 0, count);
        return output.toString("UTF-8");
    }

    private static void compare(String path, Object expected, Object actual) throws Exception {
        if (expected instanceof JSONObject) {
            assertTrue(path + " object", actual instanceof JSONObject);
            JSONObject e = (JSONObject) expected, a = (JSONObject) actual;
            for (Iterator<String> keys = e.keys(); keys.hasNext();) {
                String key = keys.next();
                assertTrue(path + "." + key + " present", a.has(key));
                compare(path + "." + key, e.get(key), a.get(key));
            }
        } else if (expected instanceof JSONArray) {
            assertTrue(path + " array", actual instanceof JSONArray);
            JSONArray e = (JSONArray) expected, a = (JSONArray) actual;
            assertEquals(path + " length", e.length(), a.length());
            for (int i = 0; i < e.length(); i++) compare(path + "[" + i + "]", e.get(i), a.get(i));
        } else if (expected instanceof Number) {
            assertTrue(path + " number", actual instanceof Number);
            double e = ((Number) expected).doubleValue();
            assertEquals(path, e, ((Number) actual).doubleValue(), Math.max(0.0000001, Math.abs(e) * 0.000000000001));
        } else assertEquals(path, expected, actual);
    }
}
